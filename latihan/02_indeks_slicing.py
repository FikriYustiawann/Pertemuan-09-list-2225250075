# Latihan 2 - Indeks dan slicing
# Input  : list enam nilai
# Proses : akses indeks positif/negatif dan slicing
# Output : elemen pertama, terakhir, tiga awal, indeks 1 sampai 3
nilai = [75, 80, 65, 90, 88, 70]
print(f"Elemen pertama   : {nilai[0]}")
print(f"Elemen terakhir  : {nilai[-1]}")
print(f"Tiga elemen awal : {nilai[:3]}")
print(f"Indeks 1 sampai 3: {nilai[1:4]}")
